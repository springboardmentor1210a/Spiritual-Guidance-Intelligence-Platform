import io
from reportlab.lib.pagesizes import letter
from reportlab.pdfgen import canvas
from reportlab.lib import colors

def generate_pdf_report(
    user_name: str,
    archetype: str = "The Luminary Seeker",
    synthesis: str = "",
    palm_summary: str = "",
    tarot_cards: list = None,
    score: float = 88.5
) -> io.BytesIO:
    buffer = io.BytesIO()
    c = canvas.Canvas(buffer, pagesize=letter)
    width, height = letter
    
    # Celestial dark background
    c.setFillColor(colors.HexColor("#0f172a"))
    c.rect(0, 0, width, height, fill=1)
    
    # Golden Title Banner
    c.setFillColor(colors.HexColor("#fbbf24"))
    c.setFont("Helvetica-Bold", 22)
    c.drawString(50, height - 60, "MYSTIC INSIGHTS: CELESTIAL BLUEPRINT")
    
    # Subheader & Metadata
    c.setFillColor(colors.HexColor("#f8fafc"))
    c.setFont("Helvetica-Bold", 12)
    c.drawString(50, height - 95, f"Seeker: {user_name}")
    
    c.setFillColor(colors.HexColor("#38bdf8"))
    c.drawString(250, height - 95, f"Archetype: {archetype}")
    
    c.setFillColor(colors.HexColor("#34d399"))
    c.drawString(450, height - 95, f"Resonance: {score}%")
    
    # Decorative Divider
    c.setStrokeColor(colors.HexColor("#a855f7"))
    c.setLineWidth(1.5)
    c.line(50, height - 110, width - 50, height - 110)
    
    # Section 1: Palm Biometric Summary
    c.setFillColor(colors.HexColor("#fbbf24"))
    c.setFont("Helvetica-Bold", 14)
    c.drawString(50, height - 140, "1. Palmistry Vision & Biometric Synthesis")
    
    c.setFillColor(colors.HexColor("#e2e8f0"))
    c.setFont("Helvetica", 10)
    palm_text = palm_summary or "Deep heart line indicating high empathy; well-curved life line reflecting sustained inner vitality."
    textobject = c.beginText(50, height - 160)
    textobject.setFont("Helvetica", 10)
    textobject.setFillColor(colors.HexColor("#cbd5e1"))
    for line in palm_text.split('\n'):
        textobject.textLine(line[:90])
    c.drawText(textobject)
    
    # Section 2: Tarot Spreads
    c.setFillColor(colors.HexColor("#fbbf24"))
    c.setFont("Helvetica-Bold", 14)
    c.drawString(50, height - 210, "2. Active Tarot Alignment & Drawn Spreads")
    
    tarot_cards = tarot_cards or [
        {"position": "Past Influences", "name": "The Fool", "orientation": "Upright", "meaning": "New beginnings, spontaneity"},
        {"position": "Present Situation", "name": "Queen of Pentacles", "orientation": "Upright", "meaning": "Nurturing stability, material groundedness"},
        {"position": "Future Horizon", "name": "Four of Cups", "orientation": "Upright", "meaning": "Introspection, stillness, unseen gifts"}
    ]
    
    y = height - 235
    for idx, card in enumerate(tarot_cards[:5]):
        c.setFillColor(colors.HexColor("#c084fc"))
        c.setFont("Helvetica-Bold", 10)
        pos = card.get("position", f"Card {idx+1}")
        name = card.get("name", "Unknown Card")
        orient = card.get("orientation", "Upright")
        c.drawString(50, y, f"• {pos}: {name} ({orient})")
        
        c.setFillColor(colors.HexColor("#94a3b8"))
        c.setFont("Helvetica-Oblique", 9)
        meaning = card.get("meaning", "")
        c.drawString(70, y - 14, meaning[:85])
        y -= 32
        
    # Section 3: Oracle Guidance
    c.setFillColor(colors.HexColor("#fbbf24"))
    c.setFont("Helvetica-Bold", 14)
    c.drawString(50, y - 15, "3. Oracle Synthesis & Life Trend Forecast")
    
    oracle_text = synthesis or "Your energetic field demonstrates strong creative alignment and deep intuitive grounding. Embrace opportunities with steady focus."
    textobject2 = c.beginText(50, y - 35)
    textobject2.setFont("Helvetica", 10)
    textobject2.setFillColor(colors.HexColor("#e2e8f0"))
    for line in oracle_text.split('\n'):
        textobject2.textLine(line[:95])
    c.drawText(textobject2)
    
    # Footer
    c.setStrokeColor(colors.HexColor("#334155"))
    c.setLineWidth(0.5)
    c.line(50, 45, width - 50, 45)
    c.setFont("Helvetica", 8)
    c.setFillColor(colors.HexColor("#64748b"))
    c.drawString(50, 30, "Generated by Mystic Insights Intelligence Platform — Powered by MediaPipe, Swiss Ephemeris & AI")
    
    c.showPage()
    c.save()
    
    buffer.seek(0)
    return buffer